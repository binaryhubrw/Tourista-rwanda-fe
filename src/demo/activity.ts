function fee(total: number) {
  return Math.round(total * SUBSCRIPTION_RATE);
}

function pay(id: string, total: number, method: Payment['method'], at: string, status: Payment['status'], extra?: Partial<Payment>): Payment {
  const amount = status === 'Pending' ? Math.max(1, Math.ceil(total * MIN_PAY_RATE)) : total;
  return {
    id,
    method,
    status,
    ledger: status === 'Paid' ? 'approved' : status === 'Refunded' ? 'refunded' : 'pending',
    account: method === 'card' ? '**** 4242' : method === 'mtn' ? '0788 *** 111' : '0733 *** 222',
    senderName: extra?.senderName ?? 'Guest',
    reference: extra?.reference ?? id.replace('pay-', 'TR-').toUpperCase(),
    amountRwf: extra?.amountRwf ?? amount,
    minDueRwf: Math.max(1, Math.ceil(total * MIN_PAY_RATE)),
    feeRwf: fee(total),
    paidAt: at,
    sentTo: method === 'card' ? '4001234567890' : method === 'mtn' ? '0788123456' : '0733123456',
    sentToLabel: method === 'card' ? 'Kigali Wheels · Bank' : method === 'mtn' ? 'Kigali Wheels · MTN MoMo' : 'Kigali Wheels · Airtel Money',
    ...extra,
  };
}

function line(id: string, name: string, units: number, price: number, plate?: string) {
  return { serviceId: id, serviceName: name, units, unitPriceRwf: price, lineTotalRwf: units * price, plateNumbers: plate ? [plate] : undefined };
}

