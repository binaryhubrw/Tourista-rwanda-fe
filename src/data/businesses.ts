const kindFromCategory = (category: Business['category']) =>
  ({ Restaurants: 'Restaurant', 'Tour Guides': 'Tour guide', Handcrafts: 'Handcraft', 'Local Products': 'Local product', Transportation: 'Transportation', 'Community Tourism': 'Community tourism', Accommodation: 'Hotel' })[category];

function scaled(priceLevel: number, amount: number) {
  const factor = priceLevel === 1 ? 1 : priceLevel === 2 ? 1.35 : 1.8;
  return Math.round((amount * factor) / 500) * 500;
}

function presetServices(business: Business): Service[] {
  const daily = (category: string, group: OfferingGroup, amount: number, spots: number): Service => ({
    id: `${business.id}-${category.toLowerCase().replace(/\s+/g, '-')}`,
    name: category,
    category,
    group,
    description: offeringBlurb(group, category),
    priceRwf: scaled(business.priceLevel, amount),
    unit: 'per person',
    available: spots,
  });
  const wellness = WELLNESS_CATEGORIES.map((category, index) => daily(category, 'wellness', [20000, 5000, 12000, 35000, 8000][index], [6, 20, 4, 6, 10][index]));
  const food = FOOD_CATEGORIES.map((category, index) => daily(category, 'food', [18000, 8000, 4000][index], [40, 40, 40][index]));
  if (business.category === 'Accommodation') {
    if (business.propertyType === 'House' || business.propertyType === 'Apartment') return food.filter((item) => item.category !== 'Bar');
    if (business.propertyType === 'Guesthouse') return [...wellness.filter((item) => item.category !== 'Gym' && item.category !== 'Yoga'), ...food];
    return [...wellness, ...food];
  }
  if (business.category === 'Restaurants') return food.filter((item) => item.category !== 'Restaurant');
  return [];
}

function enrichBusiness(business: Business): Business {
  const rooms = business.services.filter((service) => service.unit === 'per night').sort((a, b) => a.priceRwf - b.priceRwf);
  const others = business.services.filter((service) => service.unit !== 'per night');
  const taggedRooms = rooms.map((service, index) => ({
    ...service,
    group: 'room' as const,
    category: service.category ?? ROOM_CATEGORIES[Math.min(index, ROOM_CATEGORIES.length - 1)],
  }));
  const taggedOthers = others.map((service) => {
    if (!service.group && business.category === 'Restaurants') return { ...service, group: 'food' as const, category: 'Restaurant' };
    return { ...service, group: service.group ?? ('activity' as const), category: service.category ?? service.name };
  });
  const have = new Set<string>();
  for (const service of [...taggedRooms, ...taggedOthers]) if (service.category) have.add(service.category);
  const added = presetServices(business).filter((service) => !!service.category && !have.has(service.category));
  return {
    ...business,
    listingKind: business.listingKind ?? business.propertyType ?? kindFromCategory(business.category),
    services: [...taggedRooms, ...taggedOthers, ...added],
  };
}

export const businessesSeed: Business[] = [...accommodations, ...restaurants, ...others].map(enrichBusiness);
